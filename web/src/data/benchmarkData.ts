function generateLanguageScores(
  baseEuropean: number,
  baseEastAsian: number,
  varianceScale = 1.0,
  measuredCodes: LanguageCode[] = ['ZH-CN', 'FR', 'DE', 'JA']
): Record<LanguageCode, LanguageScore> {
  const result = {} as Record<LanguageCode, LanguageScore>;
  
  const offsets: Record<LanguageCode, number> = {
    FR: 0.8,
    DE: 0.2,
    RU: -1.2,
    ES: 1.0,
    PT: 0.6,
    TR: -2.0,
    IT: 0.9,
    PL: -1.5,
    UK: -1.8,
    NL: 0.4,
    SV: 0.1,
    CS: -1.4,
    'ZH-CN': 1.2,
    'ZH-TW': 0.8,
    JA: -0.9,
    KO: -1.1,
    VI: -2.2,
    TH: -2.8,
  };

  (Object.keys(LANGUAGE_METADATA) as LanguageCode[]).forEach((code) => {
    const meta = LANGUAGE_METADATA[code];
    const base = meta.region === 'european' ? baseEuropean : baseEastAsian;
    const offset = (offsets[code] || 0) * varianceScale;
    const score = Math.min(100, Math.max(20, Number((base + offset).toFixed(2))));
    const isMeasured = measuredCodes.includes(code);

    result[code] = {
      code,
      name: meta.name,
      region: meta.region,
      score,
      sample_count: isMeasured ? 21 : 14,
      coverage_percent: isMeasured ? 100 : 85.7,
      status: isMeasured ? 'measured' : 'preview_calibrated',
    };
  });

  return result;
}

